#!/usr/bin/env python3
"""Build FINAL_SUBMISSION_PACKAGE/source_code/COMPLETE_SOURCE_CODE_AND_EXPERIMENTS.zip.

The archive preserves the repository's directory structure so that a reader can unpack it
and run the commands in the README unchanged.

Three classes of file are deliberately excluded and the exclusion is enforced here rather
than left to a .gitignore, because this archive leaves the repository:

  1. Anything that could hold a credential. secrets.h is excluded by name; secrets.example.h
     is INCLUDED, because its demonstration key is published on purpose and the build refuses
     to accept it as a real key. Certificates, keys and password files generated by the broker
     testbed are excluded.
  2. Build output and caches, which are large and regenerate.
  3. The model checker's trace files and its 4.5 MB jar, which are artefacts of a run rather
     than source.

Every excluded path is listed in the manifest with its reason, so the exclusion is visible to
whoever unpacks the archive. The script then re-scans the archive for anything that looks like
key material and fails if it finds any.
"""
from __future__ import annotations

import hashlib
import re
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT_DIR = ROOT / "FINAL_SUBMISSION_PACKAGE" / "source_code"
OUT_ZIP = OUT_DIR / "COMPLETE_SOURCE_CODE_AND_EXPERIMENTS.zip"

# Directories never archived, with the reason recorded in the manifest.
SKIP_DIRS = {
    ".git": "version-control metadata",
    ".github": "included selectively below",
    "__pycache__": "Python bytecode cache",
    ".pytest_cache": "test-runner cache",
    "node_modules": "dependency cache",
    "build": "build output",
    "corpus_repos": "third-party source fetched for the corpus study",
    "states": "model-checker run state",
    # The archive lives inside FINAL_SUBMISSION_PACKAGE, and that directory is a collection of
    # copies of files already present at their own paths. Including it would nest the figure
    # collection zip inside this one and duplicate every PDF.
    "FINAL_SUBMISSION_PACKAGE": "assembled package; its contents appear at their source paths",
    "media": "demonstration video and GIF; 11 MB, not source",
}

# Exact filenames never archived.
SKIP_NAMES = {
    "secrets.h": "may contain real credentials",
    "tla2tools.jar": "4.5 MB binary; downloaded by formal/run_tlc.sh",
    ".DS_Store": "platform metadata",
}

# Suffix patterns never archived.
SKIP_SUFFIXES = {
    ".pyc": "bytecode",
    ".o": "object file",
    ".so": "shared object",
    ".bin": "model-checker trace",
    ".aux": "LaTeX intermediate",
    ".log": "LaTeX or run log",
    ".out": "LaTeX intermediate",
    ".toc": "LaTeX intermediate",
    ".lof": "LaTeX intermediate",
    ".lot": "LaTeX intermediate",
    ".blg": "LaTeX intermediate",
    ".bbl": "LaTeX intermediate",
    ".synctex.gz": "LaTeX intermediate",
    ".key": "private key material",
    ".pem": "certificate or key material",
    ".crt": "certificate material",
    ".csr": "certificate request",
}

SKIP_GLOBS = [
    ("AlarmFSM_TTrace_*", "model-checker trace file"),
    ("passwd*", "broker password file"),
    ("*.pwd", "broker password file"),
    ("results_hw.csv", "would be real hardware data; none exists"),
]

# Anything matching these in a FILE'S CONTENT fails the build, unless the path is a known
# published demonstration value.
#
# The PEM patterns require an actual base64 body of at least two full lines after the header,
# not merely the header line. Four files in the repository contain the header as a build-flag
# placeholder -- "-----BEGIN CERTIFICATE-----\ntest\n..." in run_ablation.sh, a bare header in
# run_tests.sh, and "...\n" in the HARDENING.md example. Matching on the header alone flags all
# four and would push a reader towards allow-listing those paths, which would then also let
# real material through if it were ever added to them. Requiring the body distinguishes a
# placeholder from a key.
SECRET_PATTERNS = [
    (re.compile(rb"-----BEGIN [A-Z ]*PRIVATE KEY-----[\r\n]+[A-Za-z0-9+/=]{60,}[\r\n]+"
                rb"[A-Za-z0-9+/=]{20,}"), "private key block"),
    (re.compile(rb"-----BEGIN CERTIFICATE-----[\r\n]+[A-Za-z0-9+/=]{60,}[\r\n]+"
                rb"[A-Za-z0-9+/=]{20,}"), "certificate block"),
    (re.compile(rb"(?i)\bAKIA[0-9A-Z]{16}\b"), "AWS access key id"),
    (re.compile(rb"(?i)gh[pousr]_[A-Za-z0-9]{36,}"), "GitHub token"),
]
SECRET_ALLOW = {
    "firmware/smart_home/secrets.example.h",  # published demonstration values, by design
}


def reason_to_skip(path: Path) -> str | None:
    rel = path.relative_to(ROOT)
    for part in rel.parts[:-1]:
        if part in SKIP_DIRS:
            return SKIP_DIRS[part]
    if path.name in SKIP_NAMES:
        return SKIP_NAMES[path.name]
    for suffix, why in SKIP_SUFFIXES.items():
        if path.name.endswith(suffix):
            return why
    for pattern, why in SKIP_GLOBS:
        if path.match(pattern):
            return why
    return None


def main() -> int:
    OUT_DIR.mkdir(parents=True, exist_ok=True)

    included: list[Path] = []
    excluded: list[tuple[Path, str]] = []

    for path in sorted(ROOT.rglob("*")):
        if not path.is_file() or path.is_symlink():
            continue
        if OUT_DIR in path.parents:
            continue
        why = reason_to_skip(path)
        if why:
            excluded.append((path.relative_to(ROOT), why))
        else:
            included.append(path)

    # Refuse to build an archive containing key material.
    problems = []
    for path in included:
        rel = str(path.relative_to(ROOT))
        if rel in SECRET_ALLOW:
            continue
        try:
            blob = path.read_bytes()
        except OSError:
            continue
        for pattern, label in SECRET_PATTERNS:
            if pattern.search(blob):
                problems.append(f"{rel}: {label}")
    if problems:
        print("REFUSING to build the archive; possible secrets found:", file=sys.stderr)
        for p in problems:
            print(f"  {p}", file=sys.stderr)
        return 1

    manifest = [
        "COMPLETE SOURCE CODE AND EXPERIMENTS",
        "=" * 60,
        "",
        f"Files included: {len(included)}",
        f"Files excluded: {len(excluded)}",
        "",
        "Every path below is relative to the archive root and matches its path in the",
        "repository, so the commands in README_SOURCE.md run unchanged after unpacking.",
        "",
        "SHA-256 of each included file:",
        "",
    ]
    for path in included:
        digest = hashlib.sha256(path.read_bytes()).hexdigest()
        manifest.append(f"{digest}  {path.relative_to(ROOT)}")

    manifest += ["", "EXCLUDED, with the reason:", ""]
    for rel, why in excluded:
        manifest.append(f"{rel}  --  {why}")

    with zipfile.ZipFile(OUT_ZIP, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        for path in included:
            z.write(path, arcname=str(path.relative_to(ROOT)))
        z.writestr("MANIFEST.txt", "\n".join(manifest) + "\n")

    size = OUT_ZIP.stat().st_size
    print(f"wrote {OUT_ZIP.relative_to(ROOT)}")
    print(f"  {len(included)} files, {len(excluded)} excluded, {size/1e6:.2f} MB")
    print(f"  sha256 {hashlib.sha256(OUT_ZIP.read_bytes()).hexdigest()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

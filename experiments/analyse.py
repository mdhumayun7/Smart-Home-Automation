#!/usr/bin/env python3
"""Aggregate the adversarial campaign results into the tables and figures used in the paper.

Reads results/campaign_baseline.jsonl and results/campaign_hardened.jsonl, computes per-rate
statistics, runs a non-parametric test comparing the safety-latency distribution under attack
against the no-attack baseline, and writes:

    results/summary.md     human-readable tables
    results/summary.json   machine-readable aggregates
    results/fig_*.png      figures

Usage: python3 analyse.py
"""
import json
import os
import statistics
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, "results")


def load(name):
    rows = []
    path = os.path.join(RES, name)
    with open(path) as f:
        for line in f:
            line = line.strip()
            if line:
                rows.append(json.loads(line))
    return rows


def mann_whitney_u(a, b):
    """Two-sided Mann-Whitney U test. Returns (U, z, p) using the normal approximation with
    a tie correction. Implemented here to avoid a SciPy dependency."""
    n1, n2 = len(a), len(b)
    if n1 == 0 or n2 == 0:
        return None, None, None
    combined = sorted([(v, 0) for v in a] + [(v, 1) for v in b])
    # average ranks for ties
    ranks = [0.0] * len(combined)
    i = 0
    tie_term = 0.0
    while i < len(combined):
        j = i
        while j + 1 < len(combined) and combined[j + 1][0] == combined[i][0]:
            j += 1
        avg = (i + j) / 2.0 + 1.0
        t = j - i + 1
        tie_term += t ** 3 - t
        for k in range(i, j + 1):
            ranks[k] = avg
        i = j + 1
    r1 = sum(r for r, (_, grp) in zip(ranks, combined) if grp == 0)
    u1 = r1 - n1 * (n1 + 1) / 2.0
    u2 = n1 * n2 - u1
    u = min(u1, u2)
    mu = n1 * n2 / 2.0
    n = n1 + n2
    sigma_sq = (n1 * n2 / 12.0) * ((n + 1) - tie_term / (n * (n - 1))) if n > 1 else 0.0
    if sigma_sq <= 0:
        # All values identical: distributions are indistinguishable.
        return u, 0.0, 1.0
    z = (u - mu) / (sigma_sq ** 0.5)
    # two-sided p from the normal approximation
    import math
    p = math.erfc(abs(z) / math.sqrt(2))
    return u, z, p


def summarise(rows, label):
    by_rate = defaultdict(list)
    for r in rows:
        by_rate[r["attack_rate"]].append(r)

    out = {"label": label, "trials": len(rows), "rates": {}}
    for rate in sorted(by_rate):
        rs = by_rate[rate]
        lat = [r["safety_latency_ms"] for r in rs if r.get("reached_alarm")]
        alarm = [r["alarm_latency_ms"] for r in rs if r.get("reached_alarm")]
        out["rates"][rate] = {
            "n": len(rs),
            "reached_alarm": sum(1 for r in rs if r.get("reached_alarm")),
            "violations": sum(1 for r in rs if r.get("violation")),
            "violation_kinds": sorted({r["violation"] for r in rs if r.get("violation")}),
            "attacker_armed": sum(1 for r in rs if r.get("attacker_armed")),
            "attacker_disarmed": sum(1 for r in rs if r.get("attacker_disarmed")),
            "legit_accepted": sum(1 for r in rs if r.get("legit_cmd_accepted")),
            "latency_min": min(lat) if lat else None,
            "latency_median": statistics.median(lat) if lat else None,
            "latency_max": max(lat) if lat else None,
            "latency_stdev": (statistics.pstdev(lat) if len(lat) > 1 else 0.0),
            "alarm_latency_median": statistics.median(alarm) if alarm else None,
            "event_drops_total": sum(r.get("event_drops", 0) for r in rs),
            "_lat": lat,
        }
    return out


def fmt(v):
    return "-" if v is None else (f"{v:g}" if isinstance(v, float) else str(v))


def main():
    base = summarise(load("campaign_baseline.jsonl"), "baseline (no command authentication)")
    hard = summarise(load("campaign_hardened.jsonl"), "hardened (AUTH_COMMANDS=1)")

    lines = []
    lines.append("# Adversarial campaign results\n")
    lines.append("Generated by `experiments/analyse.py` from the campaign JSONL files. "
                 "Every trial is reproducible from its seed.\n")

    for s in (base, hard):
        lines.append(f"\n## {s['label']}\n")
        lines.append(f"Trials: {s['trials']}\n")
        lines.append("| attack rate (msg/s) | n | reached alarm | safety latency med (ms) "
                     "| min | max | sd | attacker armed | attacker disarmed | legit cmd took effect | invariant violations |")
        lines.append("|---|---|---|---|---|---|---|---|---|---|---|")
        for rate in sorted(s["rates"]):
            d = s["rates"][rate]
            lines.append(
                f"| {rate} | {d['n']} | {d['reached_alarm']} | {fmt(d['latency_median'])} "
                f"| {fmt(d['latency_min'])} | {fmt(d['latency_max'])} | {fmt(round(d['latency_stdev'],3))} "
                f"| {d['attacker_armed']} | {d['attacker_disarmed']} | {d['legit_accepted']} "
                f"| {d['violations']} |")

    # Hypothesis test: is the latency distribution under attack different from no attack?
    lines.append("\n## H1 (logical form): safety latency is invariant to attack rate\n")
    lines.append("**Read this with its caveat.** In simulation the device clock is advanced by the "
                 "harness, so there is no CPU contention and the latency is deterministic: the "
                 "variance is zero and the test below is trivially satisfied. What this establishes "
                 "is the *logical* claim, that no code path makes the safety response depend on "
                 "network input. The *timing* claim (H1 proper) can only be tested on hardware, "
                 "where the radio driver and the safety loop genuinely contend; the same test is "
                 "applied to that data in `experiments/hardware/`.\n")
    lines.append("Mann-Whitney U, two-sided, each attack rate against the no-attack control.\n")
    lines.append("| attack rate | n(attack) | n(control) | U | z | p | verdict |")
    lines.append("|---|---|---|---|---|---|---|")
    control = hard["rates"][0]["_lat"]
    tests = {}
    for rate in sorted(hard["rates"]):
        if rate == 0:
            continue
        lat = hard["rates"][rate]["_lat"]
        u, z, p = mann_whitney_u(lat, control)
        verdict = "indistinguishable" if (p is None or p > 0.05) else "DIFFERENT"
        tests[rate] = {"U": u, "z": z, "p": p, "verdict": verdict}
        lines.append(f"| {rate} | {len(lat)} | {len(control)} | {fmt(u)} | {fmt(None if z is None else round(z,3))} "
                     f"| {fmt(None if p is None else round(p,4))} | {verdict} |")

    # Totals
    tot_viol = sum(d["violations"] for s in (base, hard) for d in s["rates"].values())
    tot_disarm = sum(d["attacker_disarmed"] for s in (base, hard) for d in s["rates"].values())
    lines.append(f"\n**Totals.** {base['trials'] + hard['trials']} trials, "
                 f"{tot_viol} invariant violations, {tot_disarm} attacker-caused disarms.\n")

    with open(os.path.join(RES, "summary.md"), "w") as f:
        f.write("\n".join(lines) + "\n")

    # strip the raw latency lists before writing JSON
    for s in (base, hard):
        for d in s["rates"].values():
            d.pop("_lat", None)
    with open(os.path.join(RES, "summary.json"), "w") as f:
        json.dump({"baseline": base, "hardened": hard, "tests": tests}, f, indent=2)

    print("\n".join(lines))


if __name__ == "__main__":
    main()
